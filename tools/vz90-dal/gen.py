#!/usr/bin/env python3
# Build the built-in Sony VZ90 DAL from the pv-vz90-dal submodule (external/pv-vz90-dal, GPL-3.0-or-later) and
# write it where the emulator builds pick it up:
#   --native <file.cpp>  C++ source with the bundle bytes and its description (native cp-uarm)
#   --web <dir>          vz90-dal.bundle + vz90-dal.json (browser build; loaded only for a VZ90 ROM)
# The bundle is built with DAL_LOG=0 by the submodule's own Makefile (needs arm-none-eabi-gcc). Outputs are only
# rewritten when their content changes. VZ90_DAL=none in the environment builds without a built-in DAL: the native
# source then holds an empty bundle and the web directory gets no bundle (VZ90 ROMs then need a DAL given by hand).
import argparse
import hashlib
import json
import os
import shutil
import subprocess
import sys

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..'))
DAL = os.path.join(ROOT, 'external', 'pv-vz90-dal')


def fail(msg):
    sys.stderr.write('vz90-dal: ' + msg + '\n')
    sys.exit(1)


def run(cmd, **kw):
    return subprocess.run(cmd, check=True, stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True, **kw).stdout


def build():
    if not os.path.isfile(os.path.join(DAL, 'Makefile')):
        fail('the DAL source is missing: run "git submodule update --init --recursive" (external/pv-vz90-dal), '
             'or build with VZ90_DAL=none')
    if shutil.which('arm-none-eabi-gcc') is None:
        fail('arm-none-eabi-gcc not found: install the Arm GNU toolchain, or build with VZ90_DAL=none')
    try:
        run(['make', '-C', DAL, 'DAL_LOG=0', 'build/vz90-dal.bundle'])
    except subprocess.CalledProcessError as e:
        sys.stderr.write(e.stdout)
        fail('building the DAL bundle failed')
    data = open(os.path.join(DAL, 'build', 'vz90-dal.bundle'), 'rb').read()
    try:
        commit = run(['git', '-C', DAL, 'rev-parse', 'HEAD']).strip()
        dirty = bool(run(['git', '-C', DAL, 'status', '--porcelain', '--untracked-files=no']).strip())
    except (subprocess.CalledProcessError, FileNotFoundError):
        commit, dirty = 'unknown', True
    toolchain = run(['arm-none-eabi-gcc', '-dumpversion']).strip()
    build_id = data[0x18:0x18 + 20].hex() + ('-dirty' if data[0x2c] & 1 else '')
    info = {
        'source': 'pv-vz90-dal', 'sourceCommit': commit, 'sourceDirty': dirty, 'buildId': build_id,
        'sha256': hashlib.sha256(data).hexdigest(), 'size': len(data),
        'toolchain': 'arm-none-eabi-gcc ' + toolchain, 'options': 'DAL_LOG=0',
    }
    return data, info


def write_if_changed(path, content):
    mode = 'wb' if isinstance(content, bytes) else 'w'
    try:
        with open(path, 'rb' if mode == 'wb' else 'r') as f:
            if f.read() == content:
                return
    except FileNotFoundError:
        pass
    os.makedirs(os.path.dirname(path) or '.', exist_ok=True)
    with open(path, mode) as f:
        f.write(content)


def c_string(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'


def native_source(data, info):
    lines = ['// generated by tools/vz90-dal/gen.py - do not edit', '#include "vz90_dal_builtin.h"', '',
             'namespace {', '    const uint8_t bundle[] = {']
    for i in range(0, len(data), 24):
        lines.append('        ' + ','.join(str(b) for b in data[i:i + 24]) + ',')
    if not data:
        lines.append('        0')
    lines += ['    };', '}  // namespace', '',
              'const uint8_t* const vz90DalBuiltin = bundle;',
              'const size_t vz90DalBuiltinSize = %d;' % len(data),
              'const char* const vz90DalBuiltinSha256 = %s;' % c_string(info.get('sha256', '')),
              'const char* const vz90DalBuiltinSource = %s;' % c_string(
                  '' if not data else '%s %s%s, %s, %s' % (info['source'], info['sourceCommit'],
                                                          ' (modified)' if info['sourceDirty'] else '',
                                                          info['options'], info['toolchain'])), '']
    return '\n'.join(lines)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--native')
    ap.add_argument('--web')
    a = ap.parse_args()
    none = os.environ.get('VZ90_DAL', '') == 'none'
    data, info = (b'', {}) if none else build()
    if a.native:
        write_if_changed(a.native, native_source(data, info))
    if a.web:
        for name in ('vz90-dal.bundle', 'vz90-dal.json'):
            p = os.path.join(a.web, name)
            if none and os.path.exists(p):
                os.remove(p)
        if not none:
            write_if_changed(os.path.join(a.web, 'vz90-dal.bundle'), data)
            write_if_changed(os.path.join(a.web, 'vz90-dal.json'), json.dumps(info, indent=1) + '\n')
    if not none:
        sys.stderr.write('vz90-dal: built-in DAL %s, sha256 %s\n' % (info['buildId'], info['sha256']))


if __name__ == '__main__':
    main()
